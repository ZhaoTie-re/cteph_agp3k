    echo -e "${BOLD}Latest Log Messages:${NC}"
    SEP="----------------------------------------------------------------------------------------------------------------------------------------------------------------"
    echo -e "${CYAN}${SEP}${NC}"
    # Extract the last block starting with "executor >" but filter for process lines
    tail -n 100 "$LOG_FILE" | awk '/executor >/{buf=$0; next} {buf=buf ORS $0} END{print buf}' | grep -E "executor >|process >" | fold -w 160
    echo -e "${CYAN}${SEP}${NC}"
fi

